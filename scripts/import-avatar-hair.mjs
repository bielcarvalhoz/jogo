// node scripts/import-avatar-hair.mjs <extracted Universal Base Characters[Standard]>
// Copies authored CC0 geometry; only coordinates are fitted to Sato's head.
import fs from 'node:fs';
import path from 'node:path';
import * as THREE from 'three';
const root = process.argv[2];
if (!root) throw new Error('Informe a pasta Universal Base Characters[Standard].');
const folder = path.join(root, 'Hairstyles/Origin at 0/glTF (Godot)'), assets = {};
const fits = { original: ['SimpleParted', 1.70, 1.30], crop: ['Buzzed', 1.70, 1.36], long: ['Long', 1.66, 1.25], buns: ['Buns', 1.66, 1.25], sidecut: ['BuzzedFemale', 1.66, 1.32] };
for (const [style, [name, centerY, width]] of Object.entries(fits)) {
  const json = JSON.parse(fs.readFileSync(path.join(folder, `Hair_${name}.gltf`))), node = json.nodes.find(n => n.mesh !== undefined);
  const primitive = json.meshes[node.mesh].primitives[0], buffers = json.buffers.map(b => fs.readFileSync(path.join(folder, b.uri)));
  function read(id) {
    const accessor = json.accessors[id], view = json.bufferViews[accessor.bufferView], bytes = buffers[view.buffer];
    const components = { SCALAR: 1, VEC2: 2, VEC3: 3 }[accessor.type], size = accessor.componentType === 5126 ? 4 : accessor.componentType === 5123 ? 2 : 1, values = [];
    const offset = (view.byteOffset || 0) + (accessor.byteOffset || 0), stride = view.byteStride || components * size;
    for (let i = 0; i < accessor.count; i++) for (let c = 0; c < components; c++) {
      const at = offset + i * stride + c * size;
      values.push(accessor.componentType === 5126 ? bytes.readFloatLE(at) : accessor.componentType === 5123 ? bytes.readUInt16LE(at) : bytes.readUInt8(at));
    }
    return values;
  }
  const matrix = new THREE.Matrix4().compose(new THREE.Vector3(...(node.translation || [0, 0, 0])), new THREE.Quaternion(...(node.rotation || [0, 0, 0, 1])), new THREE.Vector3(...(node.scale || [1, 1, 1])));
  const geometry = new THREE.BufferGeometry();
  geometry.setAttribute('position', new THREE.Float32BufferAttribute(read(primitive.attributes.POSITION), 3));
  geometry.setAttribute('normal', new THREE.Float32BufferAttribute(read(primitive.attributes.NORMAL), 3));
  geometry.setAttribute('uv', new THREE.Float32BufferAttribute(read(primitive.attributes.TEXCOORD_0), 2));
  geometry.setIndex(read(primitive.indices)); geometry.applyMatrix4(matrix);
  geometry.translate(0, -centerY, 0); geometry.scale(width, .95, 1.14); geometry.translate(0, .858, -.009);
  geometry.computeVertexNormals();
  const rounded = attribute => Array.from(geometry.attributes[attribute].array, n => Number(n.toFixed(6)));
  assets[style] = { source: `Hair_${name}`, position: rounded('position'), normal: rounded('normal'), uv: rounded('uv'), index: Array.from(geometry.index.array) };
}
fs.writeFileSync('src/player/hair-assets.js', `// Generated by scripts/import-avatar-hair.mjs. Quaternius, CC0-1.0.\nexport default ${JSON.stringify(assets)};\n`);
fs.mkdirSync('public/models/hair', { recursive: true });
fs.writeFileSync('public/models/hair/LICENSE-Quaternius.txt', fs.readFileSync(path.join(root, 'License_Standard.txt'), 'utf8').replace(/[ \t]+(?=\r?$)/gm, ''));
console.log('Imported', Object.keys(assets).length, 'authored hairstyles.');
